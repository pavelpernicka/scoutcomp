/**
 * Returns GrapesJS i18n config for the current React language. Falls back to
 * the English defaults shipped by GrapesJS when the language is unsupported.
 */
export function grapesI18nConfig(language = "cs") {
  if (language === "cs") {
    return {
      locale: "cs",
      detectLocale: false,
      messagesAdd: { cs: GRAPES_CS_MESSAGES },
    };
  }
  return { locale: "en", detectLocale: false };
}
